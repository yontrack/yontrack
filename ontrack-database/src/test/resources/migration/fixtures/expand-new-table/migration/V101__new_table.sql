(
    ID   SERIAL PRIMARY KEY NOT NULL,
    NAME VARCHAR(100)       NOT NULL
);
CREATE INDEX NEW_STUFF_IX_NAME ON NEW_STUFF (NAME);
ALTER TABLE NEW_STUFF
    ADD COLUMN BUILD_ID INTEGER NOT NULL,
    ADD CONSTRAINT NEW_STUFF_FK_BUILD FOREIGN KEY (BUILD_ID) REFERENCES BUILDS (ID) ON DELETE CASCADE;
ALTER TABLE NEW_STUFF
    ALTER COLUMN NAME SET NOT NULL;
