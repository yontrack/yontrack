    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE PROMOTION_RUNS
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE VALIDATION_RUN_STATUSES
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE EVENTS
    ALTER COLUMN EVENT_USER TYPE VARCHAR(200);

ALTER TABLE ENV_SLOT_PIPELINE_CHANGE
    ALTER COLUMN "USER" TYPE VARCHAR(200);
ALTER TABLE ENV_SLOT_PIPELINE_ADMISSION_RULE_STATUS
    ALTER COLUMN DATA_USER TYPE VARCHAR(200),
    ALTER COLUMN OVERRIDE_USER TYPE VARCHAR(200);
ALTER TABLE ENV_SLOT_WORKFLOW_INSTANCES
    ALTER COLUMN "USER" TYPE VARCHAR(200);

ALTER TABLE PROJECTS
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE BRANCHES
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE PROMOTION_LEVELS
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE VALIDATION_STAMPS
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE RUN_INFO
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
ALTER TABLE ENTITY_DATA_STORE
    ALTER COLUMN CREATOR TYPE VARCHAR(200);
