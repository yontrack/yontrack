    ALTER COLUMN CREATOR TYPE VARCHAR(200);

-- 2. The actor of a signature, when it is an agent - NULL is a person, and there is no backfill:
--    {"kind": "agent", "agent": "<slug>[agent]", "displayName": ..., "tool": ..., "owner": "<email>", "session": {"id": ..., "link": ...}}
--    The names are copied, so that they survive the deletion of the agent.

ALTER TABLE BUILDS
    ADD COLUMN ACTOR JSONB NULL;
ALTER TABLE PROMOTION_RUNS
    ADD COLUMN ACTOR JSONB NULL;
ALTER TABLE VALIDATION_RUN_STATUSES
    ADD COLUMN ACTOR JSONB NULL;
ALTER TABLE EVENTS
    ADD COLUMN ACTOR JSONB NULL;
ALTER TABLE ENV_SLOT_PIPELINE_CHANGE
    ADD COLUMN ACTOR JSONB NULL;

-- 3. The events of an agent

CREATE INDEX EVENTS_IX_ACTOR_AGENT ON EVENTS ((ACTOR ->> 'agent')) WHERE ACTOR IS NOT NULL;
