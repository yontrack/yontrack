package net.nemerosa.ontrack.service.security

import net.nemerosa.ontrack.model.security.ConfidentialStore
import net.nemerosa.ontrack.model.security.EncryptionException
import net.nemerosa.ontrack.model.support.ReadMemo
import java.io.IOException
import java.security.GeneralSecurityException
import java.util.*
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.SecretKeySpec

/**
 * AES key kept in the confidential store, the same for all the replicas (#2086).
 *
 * The key is generated once for all of them, under a lock across the replicas, and read back from
 * the store: two replicas needing it at the same time use the one the store keeps.
 *
 * Each generation and each import bumps the version of the key ([ConfidentialKeyVersions]). A
 * replica holds the key in memory with its version, and checks the version before encrypting or
 * decrypting: once per unit of work ([ReadMemo]) - an HTTP request, a queue message - and on each
 * use outside of one, in the jobs. A newer version loads the key again from the store, so that a
 * key imported through one replica is used by all of them for their next encryption and decryption.
 */
class CryptoConfidentialKey(
    private val confidentialStore: ConfidentialStore,
    override val id: String,
    private val versions: ConfidentialKeyVersions,
) : ConfidentialKey {

    /**
     * Key loaded from the store, and its version when it was loaded
     */
    private class Loaded(val version: Long, val secret: SecretKey)

    @Volatile
    private var loaded: Loaded? = null

    override fun exportKey(): String? {
        val payload = confidentialStore.load(id)
        return if (payload != null) {
            Base64.getEncoder().encodeToString(payload)
        } else {
            null
        }
    }

    @Synchronized
    override fun importKey(key: String) {
        val payload = Base64.getDecoder().decode(key)
        val version = versions.exclusively(id) {
            confidentialStore.store(id, payload)
            versions.bump(id)
        }
        use(Loaded(version, secretOf(payload)))
    }

    private val key: SecretKey
        get() = try {
            current().secret
        } catch (e: IOException) {
            throw Error("Failed to load the key: $id", e)
        }

    /**
     * The key of the current version, as loaded from the store
     */
    private fun current(): Loaded {
        val version = ReadMemo.read(VERSIONS, id) { versions.getVersion(id) }
        return loaded?.takeIf { it.isCurrent(version) } ?: synchronized(this) { reload() }
    }

    private fun Loaded.isCurrent(version: Long?) = version != null && this.version >= version

    private fun reload(): Loaded {
        // Not the version of the memo, which may be older than the one of the database
        val version = versions.getVersion(id)
        loaded?.takeIf { it.isCurrent(version) }?.let {
            ReadMemo.written(VERSIONS, id, version)
            return it
        }
        // The store has the key of a version once the version is bumped
        val payload = version?.let { confidentialStore.load(id) }
        return use(
            if (version != null && payload != null) {
                Loaded(version, secretOf(payload))
            } else {
                generate()
            }
        )
    }

    /**
     * Generates the key, if the store has none, while no other replica does, and reads it back from
     * the store.
     */
    private fun generate(): Loaded {
        val version = versions.exclusively(id) {
            if (confidentialStore.load(id) == null) {
                confidentialStore.store(id, confidentialStore.randomBytes(256))
                versions.bump(id)
            } else {
                // Generated by another replica, or stored before the versions of the keys (#2086)
                versions.getVersion(id) ?: versions.bump(id)
            }
        }
        val payload = confidentialStore.load(id)
            ?: throw IOException("The key $id cannot be read back from the store")
        return Loaded(version, secretOf(payload))
    }

    private fun use(key: Loaded): Loaded {
        loaded = key
        ReadMemo.written(VERSIONS, id, key.version)
        return key
    }

    // Due to the stupid US export restriction JDK only ships 128bit version.
    private fun secretOf(payload: ByteArray): SecretKey = SecretKeySpec(payload, 0, 128 / 8, ALGORITHM)

    override fun encrypt(plain: String): String {
        return try {
            // Creates a cipher
            val cipher = encrypt()
            // Message as bytes
            val bytes = plain.toByteArray(charset("UTF-8"))
            // Encryption
            val encryptedBytes = cipher.doFinal(bytes)
            // Base64 encoding
            Base64.getEncoder().encodeToString(encryptedBytes)
        } catch (ex: GeneralSecurityException) {
            throw EncryptionException(ex)
        } catch (ex: IOException) {
            throw EncryptionException(ex)
        }
    }

    override fun decrypt(crypted: String): String {
        return try {
            // Creates a cipher
            val cipher = decrypt()
            // Decodes from Base64
            val encryptedBytes = Base64.getDecoder().decode(crypted)
            // Decrypts
            val bytes = cipher.doFinal(encryptedBytes)
            // As UTF-8 string
            String(bytes, Charsets.UTF_8)
        } catch (ex: GeneralSecurityException) {
            throw EncryptionException(ex)
        } catch (ex: IOException) {
            throw EncryptionException(ex)
        }
    }

    /**
     * Returns a [javax.crypto.Cipher] object for encrypting with this key.
     */
    override fun encrypt(): Cipher {
        return try {
            val cipher = Cipher.getInstance(ALGORITHM)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher
        } catch (e: GeneralSecurityException) {
            throw AssertionError(e)
        }
    }

    /**
     * Returns a [javax.crypto.Cipher] object for decrypting with this key.
     */
    override fun decrypt(): Cipher {
        return try {
            val cipher = Cipher.getInstance(ALGORITHM)
            cipher.init(Cipher.DECRYPT_MODE, key)
            cipher
        } catch (e: GeneralSecurityException) {
            throw AssertionError(e)
        }
    }

    companion object {
        private const val ALGORITHM = "AES"

        /**
         * Versions of the keys read in a unit of work, by ID of key
         */
        private val VERSIONS = ReadMemo.Region<String, Long?>("confidential-key-versions")
    }

}
